test('dragging a block by its handle reorders it, and the saved order matches', async ({ page }) => {
  await seed(page)
  await edit(page)
  await page.locator('.doc-editing h2').hover()
  const grip = page.getByRole('button', { name: 'Block menu' }), box = await grip.boundingBox(), ul = await page.locator('.doc-editing ul').boundingBox()
  if (!box || !ul) throw new Error('no handle')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x, ul.y + ul.height / 2, { steps: 4 })
  await page.mouse.move(box.x, ul.y + ul.height + 10, { steps: 4 })
  await page.mouse.up()
  await expect.poll(() => order(page)).toEqual(['p First paragr', 'ul onetwo', 'h2 Plan'])
  await page.keyboard.press(`${mod}+s`)
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeVisible()
  expect((await saved(page)).text).toMatch(/First paragraph here\.\n\n- one\n- two\n\n## Plan \{#plan\}\n$/)
})

